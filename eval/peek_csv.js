const fs = require('fs');
const csvPath = 'C:\\Users\\matan\\Downloads\\archive_dataset\\benchmark_ai_detection_multimodel_2026.csv';
const lines = fs.readFileSync(csvPath, 'utf8').split('\n').filter(l => l.trim());

// parse header
const headers = lines[0].split(',');
const textIdx = headers.indexOf('text_content');
const labelIdx = headers.indexOf('is_ai_generated');
const modelIdx = headers.indexOf('source_model');
const wordIdx = headers.indexOf('word_count');

let aiCount = 0, humanCount = 0;
const models = {};

for (let i = 1; i < lines.length; i++) {
  // simple split — text_content is quoted so find label after last quote
  const line = lines[i];
  const isAI = line.match(/,([01]),/g);
  // get is_ai_generated by finding the field
  const parts = line.split(',');
  const label = parts[labelIdx];
  if (label === '1') aiCount++;
  else if (label === '0') humanCount++;

  // get model
  const model = parts[modelIdx];
  models[model] = (models[model] || 0) + 1;
}

console.log('AI rows:', aiCount);
console.log('Human rows:', humanCount);
console.log('\nModels:', JSON.stringify(models, null, 2));

// show a human example
console.log('\n--- Human text example ---');
for (let i = 1; i < lines.length; i++) {
  const parts = lines[i].split(',');
  if (parts[labelIdx] === '0') {
    console.log('Model:', parts[modelIdx]);
    // find text_content (quoted)
    const textStart = lines[i].indexOf('"');
    const textEnd = lines[i].lastIndexOf('"');
    if (textStart !== -1) {
      console.log('Text:', lines[i].substring(textStart, Math.min(textStart + 400, textEnd)));
    }
    break;
  }
}
